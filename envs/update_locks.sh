#!/usr/bin/env bash
# Regenerate the lock files next to this script from prohap.yaml. Run it after editing prohap.yaml:
#
#   envs/update_locks.sh
#
# Needs Docker that runs linux/amd64 and linux/arm64 containers (Docker Desktop on Apple Silicon does) and, for the
# macOS lock, conda on an Apple Silicon Mac (mamba solves if present; conda writes the lock, because mamba 2 leaves
# out the @EXPLICIT line). It downloads packages: a development tool, never part of a workflow run. The locks are
# replaced only when every one of them has been generated.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
image=mambaorg/micromamba:1.5.10        # the Dockerfile's base image
tmp=$(mktemp -d "${TMPDIR:-/tmp}/prohap-locks.XXXXXX")
trap 'rm -rf "$tmp"' EXIT
chmod 0777 "$tmp"                        # the container runs as its own user; on Linux it must be able to write here

# prohap.yaml up to its pip: section, and the pip requirements
awk '/^  - pip: *$/ {exit} {print}' "$here/prohap.yaml" > "$tmp/conda.yaml"
awk 'f && /^    - / {sub(/^    - /, ""); print} /^  - pip: *$/ {f = 1}' "$here/prohap.yaml" > "$tmp/pip.txt"
if [ ! -s "$tmp/pip.txt" ] || grep -qvE '^[A-Za-z0-9_.-]+==[^ =]+$' "$tmp/pip.txt"; then
    echo "prohap.yaml: the pip: section must list one name==version per line" >&2
    exit 1
fi

for target in linux/amd64:linux-64 linux/arm64:linux-aarch64; do
    platform=${target%%:*} subdir=${target##*:}
    echo "solving $subdir" >&2
    docker run --rm --platform "$platform" -v "$tmp:$tmp" -e LOCKS="$tmp" -e SUBDIR="$subdir" "$image" bash -euc '
        umask 000    # files the host user can read and remove, whatever uid the container runs as
        micromamba create -y -q -n lock -f "$LOCKS/conda.yaml" > /dev/null
        micromamba env export -n lock --explicit > "$LOCKS/prohap.$SUBDIR.lock"
        micromamba run -n lock python -m pip download -q --no-deps --only-binary=:all: \
            -r "$LOCKS/pip.txt" -d "$LOCKS/wheels"'
done

if [ "$(uname -s)-$(uname -m)" = Darwin-arm64 ]; then
    echo "solving osx-arm64" >&2
    solver=$(command -v mamba || command -v conda)
    "$solver" env create -y -q -p "$tmp/osx" -f "$tmp/conda.yaml" < /dev/null > /dev/null
    conda list -p "$tmp/osx" --explicit --md5 > "$tmp/prohap.osx-arm64.lock"
    PYTHONNOUSERSITE=1 "$tmp/osx/bin/python" -m pip download -q --no-deps --only-binary=:all: \
        -r "$tmp/pip.txt" -d "$tmp/wheels"
else
    echo "not an Apple Silicon Mac: prohap.osx-arm64.lock is kept, and the pip lock loses its macOS hashes" >&2
fi

# every conda lock must be an explicit file for its own platform
for lock in "$tmp"/prohap.*.lock; do
    subdir=$(basename "$lock" .lock); subdir=${subdir#prohap.}
    grep -qx '@EXPLICIT' "$lock" && grep -qx "# platform: $subdir" "$lock" \
        || { echo "$(basename "$lock") is not an explicit lock for $subdir" >&2; exit 1; }
done

# pip lock: each requirement with the sha256 of every wheel pip chose on the platforms above
python3 - "$tmp/pip.txt" "$tmp/wheels" > "$tmp/prohap.pip.lock" <<'EOF'
import hashlib, os, re, sys
requirements = [line.strip() for line in open(sys.argv[1]) if line.strip()]
wheels = sys.argv[2]
canonical = lambda name: re.sub(r'[-_.]+', '-', name).lower()
print('# Generated by update_locks.sh from prohap.yaml. Install with:')
print('#   python -m pip install --no-deps --only-binary=:all: --require-hashes -r prohap.pip.lock')
for requirement in requirements:
    name, version = requirement.split('==')
    hashes = sorted(hashlib.sha256(open(os.path.join(wheels, f), 'rb').read()).hexdigest()
                    for f in os.listdir(wheels)
                    if f.endswith('.whl') and canonical(f.split('-')[0]) == canonical(name)
                    and f.split('-')[1] == version)
    if not hashes:
        sys.exit(f'no wheel was downloaded for {requirement}')
    print(requirement + ' \\\n' + ' \\\n'.join(f'    --hash=sha256:{h}' for h in hashes))
EOF

cp "$tmp"/prohap.*.lock "$here/"
echo "updated: $(cd "$here" && ls prohap.*.lock | tr '\n' ' ')" >&2
